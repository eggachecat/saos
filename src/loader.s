# ============================================================================
# 内核加载器(Kernel Loader)汇编文件
# ============================================================================
# 文件目的：
#   这是操作系统启动的第一段代码，由GRUB引导加载器执行。
#   它的作用是：
#     1. 提供符合Multiboot规范的头部，让GRUB能识别并加载我们的内核
#     2. 设置基本的运行环境(如栈)
#     3. 调用C++代码之前的准备工作
#     4. 最终跳转到C++编写的内核主函数
#
# 执行顺序：
#   BIOS → GRUB → loader.s → callConstructors → kernelMain
# ============================================================================

# ============================================================================
# Multiboot规范相关常量
# ============================================================================
# 不寻常之处：Multiboot魔数和校验和
#
# 什么是Multiboot？
#   Multiboot是一个开放标准，定义了引导加载器(如GRUB)和操作系统内核
#   之间的接口。通过遵循这个标准，我们的内核可以被多种引导加载器启动。
#
# GRUB会扫描内核文件的前8192字节，寻找一个特殊的"签名"：
#   - 魔数(MAGIC): 0x1badb002
#   - 标志(FLAGS): 描述内核需要什么
#   - 校验和(CHECKSUM): 用于验证
#   这三个32位数字的和必须为0，否则GRUB会拒绝加载

.set MAGIC, 0x1badb002      # Multiboot魔数，固定值
                            # 这个奇怪的数字是标准规定的，用于标识Multiboot兼容内核

.set FLAGS, (1<<0 | 1<<1)   # 标志位(二进制: 0000...0011)
                            # 位0 (1<<0): 请求在4KB边界上对齐所有模块
                            # 位1 (1<<1): 请求提供内存信息(内存大小等)
                            # 位运算: 1<<0 = 1, 1<<1 = 2, 合起来 = 3

.set CHECKSUM, -(MAGIC + FLAGS)  # 校验和 = -(魔数 + 标志)
                                 # 这样确保 MAGIC + FLAGS + CHECKSUM = 0
                                 # 是Multiboot规范的要求

# ============================================================================
# Multiboot头部段
# ============================================================================
# 汇编模式：特殊段定义
#
# .section指令用于定义代码/数据应该放在哪个段(section)。
# 段是链接器组织程序的方式。常见的段有：
#   .text   - 代码段(可执行指令)
#   .data   - 已初始化数据段
#   .bss    - 未初始化数据段
#   .rodata - 只读数据段
#
# 这里我们定义了一个自定义段 .multiboot
# 在链接脚本(linker.ld)中，这个段会被放在内核文件的最开始，
# 这样GRUB才能找到它。

.section .multiboot
    .long MAGIC      # 放入魔数(32位)
    .long FLAGS      # 放入标志(32位)
    .long CHECKSUM   # 放入校验和(32位)
    # 这12个字节构成了最小的Multiboot头部

# ============================================================================
# 代码段开始
# ============================================================================
.section .text

# 汇编模式：外部符号引用和符号导出
#
# .extern 声明一个在其他文件中定义的符号(函数或变量)
# .global 导出一个符号，让其他文件可以引用它
#
# 这是汇编语言实现模块化编程的方式

.extern kernelMain        # 声明kernelMain函数(在kernel.cpp中定义)
                          # 这是C++编写的内核主函数
                          
.extern callConstructors  # 声明callConstructors函数(在kernel.cpp中定义)
                          # 用于调用C++全局对象的构造函数
                          
.global loader           # 导出loader符号
                         # 链接脚本会设置loader为内核的入口点
                         # GRUB会跳转到这里开始执行

# ============================================================================
# 内核入口点：loader
# ============================================================================
# 当GRUB加载完内核后，会执行以下操作：
#   1. 将CPU切换到32位保护模式
#   2. 禁用分页
#   3. 将Multiboot信息结构的地址放入EBX寄存器
#   4. 将Multiboot魔数(0x2badb002)放入EAX寄存器
#   5. 跳转到loader标签
#
# 此时的CPU状态：
#   - 保护模式，分页关闭
#   - 中断可能开启或关闭(不确定)
#   - EAX = 0x2badb002 (Multiboot魔数)
#   - EBX = 指向Multiboot信息结构的指针
#   - 栈未设置！(需要我们手动设置)

loader:
    # ========================================================================
    # 步骤1：设置栈
    # ========================================================================
    # 汇编模式：栈初始化
    #
    # 为什么需要设置栈？
    #   C/C++代码依赖栈来：
    #     - 存储局部变量
    #     - 保存函数返回地址
    #     - 传递函数参数
    #   如果不设置栈，call指令会导致系统崩溃！
    #
    # 栈在哪里？
    #   我们在.bss段分配了2MB空间作为栈
    #   kernel_stack标签指向这块空间的"顶部"(高地址端)
    #
    # 不寻常之处：栈向下增长
    #   在x86架构中，栈从高地址向低地址增长
    #   ESP(栈指针)初始指向最高地址，push会使ESP减小
    
    mov $kernel_stack, %esp
    # ESP现在指向我们分配的2MB栈空间的顶部
    # 栈已准备好，可以安全调用函数了

    # ========================================================================
    # 步骤2：调用C++全局对象的构造函数
    # ========================================================================
    # 汇编模式：C++运行时初始化
    #
    # C++的特殊之处：
    #   在main函数运行之前，C++需要：
    #     1. 调用所有全局对象的构造函数
    #     2. 调用所有静态对象的构造函数
    #     3. 初始化虚函数表等运行时结构
    #
    # 在普通程序中，这些由C++运行时库(CRT)自动完成。
    # 但我们是在写操作系统内核，没有标准的C++运行时！
    # 所以我们必须手动实现callConstructors函数来做这件事。
    #
    # callConstructors会遍历编译器生成的特殊数组(.ctors段)，
    # 调用其中的每个构造函数指针。
    
    call callConstructors
    # 现在所有C++全局对象已经初始化，可以安全使用了
    
    # ========================================================================
    # 步骤3：跳转到C++内核主函数
    # ========================================================================
    # 汇编模式：函数调用约定(Calling Convention)
    #
    # C调用约定(cdecl)规定：
    #   - 参数从右到左压栈
    #   - 返回值通过EAX传递
    #   - EAX, ECX, EDX是调用者保存的(caller-saved)
    #   - EBX, ESI, EDI, EBP是被调用者保存的(callee-saved)
    #
    # kernelMain的C++签名可能是：
    #   void kernelMain(uint32_t multiboot_magic, uint32_t multiboot_info);
    #   或者反过来，取决于你的实现
    
    # 注意：参数的顺序！
    # 假设kernelMain(magic, info)，我们需要从右到左压栈：
    push %eax   # 第二个参数：Multiboot信息结构指针(从GRUB传入)
                # 这个结构包含内存映射、命令行参数、模块信息等
                
    push %ebx   # 第一个参数：Multiboot魔数(从GRUB传入)
                # 用于验证是否被Multiboot兼容的引导加载器启动
                
    # 注：从你的注释来看，参数顺序可能反了。应该检查kernel.cpp中
    # kernelMain的实际定义。如果参数顺序错误，只需交换这两行push即可。
                
    call kernelMain
    # 跳转到C++内核主函数
    # 从这里开始，控制权交给高级语言代码

# ============================================================================
# 停机循环：_stop
# ============================================================================
# 如果kernelMain返回了(正常情况下不应该返回)，我们需要停止CPU。
# 这是一个汇编模式：安全的无限循环(Safe Infinite Loop)

_stop:
    cli    # Clear Interrupt flag - 禁用中断
           # 这是一个x86指令，清除EFLAGS寄存器中的IF标志
           # 防止中断唤醒CPU
           
    hlt    # Halt - 停机
           # 这是一个x86指令，让CPU进入低功耗等待状态
           # CPU会停止执行，直到下一个中断到来
           # 但我们已经关闭了中断，所以会一直停机
           
    jmp _stop  # 无条件跳转到_stop
               # 为什么需要这个循环？
               # 因为在某些情况下(如NMI非屏蔽中断)，CPU可能会被唤醒
               # 这个跳转确保CPU会再次执行cli和hlt，重新停机
               # 这是内核中常见的"停机并循环"模式

# ============================================================================
# BSS段：未初始化数据段
# ============================================================================
# 汇编模式：BSS段和栈分配
#
# 什么是BSS？
#   BSS(Block Started by Symbol)是一个特殊的段，用于存储未初始化的
#   静态变量。在可执行文件中，BSS段不占用磁盘空间(不存储实际的0值)，
#   只记录大小。加载器会在加载时将BSS段清零。
#
# 为什么在BSS中分配栈？
#   因为栈初始内容无所谓，不需要初始化
#   这样可以减小内核文件的大小

.section .bss
.space 2*1024*1024; # 分配2MB(2,097,152字节)的空间
                    # 这是栈的大小，应该足够内核使用
                    # 如果栈溢出(使用超过2MB)，会覆盖其他数据，导致崩溃
                    # 在实际的操作系统中，可能需要实现栈保护机制
                    
kernel_stack:       # 这个标签标记栈的"顶部"
                    # 由于栈向下增长，这实际上是栈空间的最高地址
                    # ESP会从这里开始，向下(地址减小)增长
                    
# ============================================================================
# 内存布局示意图
# ============================================================================
# 低地址
#   +-----------------------+
#   | .multiboot (12 bytes) |  <- GRUB从这里开始扫描
#   +-----------------------+
#   | .text (代码)          |  <- loader, 以及后续链接的所有代码
#   +-----------------------+
#   | .data (已初始化数据)  |
#   +-----------------------+
#   | .bss (未初始化数据)   |
#   |   [2MB空栈空间]      |  <- kernel_stack - 2MB
#   |         ↓            |
#   |      (栈向下增长)     |
#   |         ↓            |
# kernel_stack (ESP初始位置) ← 栈顶
# +-----------------------+
# 高地址
